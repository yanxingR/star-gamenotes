-- 星GN 年度评选 · 玩家投票
-- 在 Supabase Dashboard → SQL Editor 里整段执行一次。
-- 作用：创建投票表、只允许通过 submit_votes 写入、提供不含 voter_id 的聚合结果视图。
-- 本次更新包含：投票截止（每年 12-31 23:59:59 北京时间）+ 基础防刷（每 IP 10 分钟最多 12 次提交）。

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  year int not null check (year between 2023 and 2100),
  category text not null,
  game_id bigint not null check (game_id > 0),
  voter_id uuid not null,
  created_at timestamptz not null default now(),
  unique (year, category, voter_id)
);

create index if not exists votes_tally_idx
  on public.votes (year, category, game_id);

alter table public.votes enable row level security;

-- 不再允许前端直接 insert；所有写入统一走 submit_votes，避免绕过截止时间和频率限制。
drop policy if exists "votes_insert_anon" on public.votes;
revoke insert on public.votes from anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 提交日志：只保存 IP 哈希和 voter_id，用于频率限制；不对外暴露。
create table if not exists public.vote_submit_log (
  id bigint generated by default as identity primary key,
  ip_hash text,
  voter_id uuid,
  year int,
  created_at timestamptz not null default now()
);

create index if not exists vote_submit_log_ip_idx
  on public.vote_submit_log (ip_hash, created_at desc);

alter table public.vote_submit_log enable row level security;

-- 聚合结果视图：只暴露票数，不暴露 voter_id
create or replace view public.vote_totals as
select
  year,
  category,
  game_id,
  count(*)::int as votes
from public.votes
group by year, category, game_id;

grant select on public.vote_totals to anon, authenticated;

-- 修改投票：删除该浏览器本年度的旧票，再写入新票
-- 截止时间：每年的 12-31 23:59:59（Asia/Shanghai）
-- 防刷：同一 IP 哈希 10 分钟内最多 12 次提交；超过返回 RATE_LIMITED
create or replace function public.submit_votes(
  p_voter_id uuid,
  p_year int,
  p_votes jsonb
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ip text;
  v_ip_hash text;
  v_recent int;
begin
  if p_year < 2023 or p_year > 2100 then
    raise exception 'invalid year';
  end if;

  if now() > make_timestamptz(p_year, 12, 31, 23, 59, 59, 'Asia/Shanghai') then
    raise exception 'VOTING_CLOSED' using errcode = 'P0001';
  end if;

  if p_votes is null or jsonb_typeof(p_votes) <> 'array' then
    raise exception 'invalid votes';
  end if;

  if jsonb_array_length(p_votes) > 6 then
    raise exception 'too many votes';
  end if;

  v_ip := coalesce(
    (nullif(current_setting('request.headers', true), '')::jsonb)->>'x-forwarded-for',
    (nullif(current_setting('request.headers', true), '')::jsonb)->>'cf-connecting-ip',
    ''
  );
  v_ip := split_part(v_ip, ',', 1);
  v_ip_hash := case
    when nullif(trim(v_ip), '') is null then md5('voter:' || p_voter_id::text)
    else md5(trim(v_ip))
  end;

  select count(*) into v_recent
  from public.vote_submit_log
  where ip_hash = v_ip_hash
    and created_at > now() - interval '10 minutes';

  if v_recent >= 12 then
    raise exception 'RATE_LIMITED' using errcode = 'P0001';
  end if;

  delete from public.vote_submit_log
  where created_at < now() - interval '2 days';

  delete from public.votes
  where voter_id = p_voter_id and year = p_year;

  insert into public.votes (year, category, game_id, voter_id)
  select
    p_year,
    (x->>'category')::text,
    (x->>'game_id')::bigint,
    p_voter_id
  from jsonb_array_elements(p_votes) as x
  where (x->>'category') is not null
    and (x->>'game_id') ~ '^[0-9]+$'
    and (x->>'game_id')::bigint > 0
  on conflict (year, category, voter_id) do update
    set game_id = excluded.game_id,
        created_at = now();

  insert into public.vote_submit_log (ip_hash, voter_id, year)
  values (v_ip_hash, p_voter_id, p_year);
end;
$$;

grant execute on function public.submit_votes(uuid, int, jsonb) to anon, authenticated;

